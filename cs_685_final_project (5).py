"""#Mean IOU
Calculates the mean IOU for training, validation, and test datasets. Generates a table showing total mean IOU across all classes and then also mean IOU for each specific class
"""

import pandas as pd
import numpy as np
import tensorflow as tf
import os

def evaluate_and_table(dataset, model, dataset_name="Test"):
    #Labelling the eight classes
    class_names = [
        'Background', 'Human diver', 'Aquatic plants', 'Wrecks/Ruins',
        'Robots/Instruments', 'Reefs', 'Fish', 'Sea-floor'
    ]
    print(f"Evaluating model on {dataset_name} dataset, this will take several minutes")
    num_classes = len(class_names)
    total_cm = np.zeros((num_classes, num_classes))
    #Goes through each image, generates prediction masks for each class and generates a confusion matrix
    for images, masks in dataset:
        preds = model.predict(images, verbose=0)
        preds_indices = np.argmax(preds, axis=-1).flatten()
        masks_indices = tf.cast(masks, tf.int32).numpy().flatten()
        valid_mask = masks_indices != -1 #The model is not punished for pixels that have the ignore label
        v_masks = masks_indices[valid_mask]
        v_preds = preds_indices[valid_mask]
        if len(v_masks) > 0:
            indices = v_masks * num_classes + v_preds
            m = np.bincount(indices, minlength=num_classes**2).reshape(num_classes, num_classes)
            total_cm += m
    #Calculates the mean IOU
    intersection = np.diag(total_cm)
    ground_truth_set = total_cm.sum(axis=1)
    predicted_set = total_cm.sum(axis=0)
    union = ground_truth_set + predicted_set - intersection
    #Seperates IOU per class
    iou_per_class = np.divide(intersection, union, out=np.zeros_like(intersection), where=union != 0)
    acc_per_class = np.divide(intersection, ground_truth_set, out=np.zeros_like(intersection), where=ground_truth_set != 0)
    manual_pixel_acc = np.sum(intersection) / (np.sum(total_cm) + 1e-7)
    #prints results
    print(f"\n{dataset_name} Results:")
    print(f"Manual Mean IoU: {np.mean(iou_per_class):.4f}")
    print(f"Manual Global Pixel Accuracy: {manual_pixel_acc:.4f}")
    print("Ground-truth class distribution (pixels):", ground_truth_set)
    print("Predicted class distribution (pixels):   ", predicted_set)
    df_metrics = pd.DataFrame({
        'Class': class_names,
        'IoU': iou_per_class,
        'Pixel Accuracy (Recall)': acc_per_class
    })
    display(df_metrics)
    print("-" * 30)

