#This function calculates accuracy while ignoring the pixels that were labelled ignore (padded pixels)
class MaskedSparseCategoricalAccuracy(tf.keras.metrics.Metric):
    def __init__(self, name="pixel_accuracy", **kwargs):
        super().__init__(name=name, **kwargs)
        self.correct = self.add_weight(name="correct", initializer="zeros")
        self.total = self.add_weight(name="total", initializer="zeros")

    def update_state(self, y_true, y_pred, sample_weight=None):
        y_true = tf.cast(tf.squeeze(y_true, axis=-1), tf.int32)
        y_pred = tf.argmax(y_pred, axis=-1, output_type=tf.int32)
        valid = tf.not_equal(y_true, -1)
        matches = tf.equal(y_true, y_pred)
        matches = tf.cast(tf.logical_and(matches, valid), tf.float32)
        valid = tf.cast(valid, tf.float32)
        self.correct.assign_add(tf.reduce_sum(matches))
        self.total.assign_add(tf.reduce_sum(valid))

    def result(self):
        return self.correct / (self.total + 1e-7)

    def reset_state(self):
        self.correct.assign(0.0)
        self.total.assign(0.0)

#Calculates the IOU and filters out background or ignore labelled pixels
class SparseMeanIoU(tf.keras.metrics.MeanIoU):
    def __init__(self, num_classes, name='total_mean_iou', dtype=None):
        super(SparseMeanIoU, self).__init__(num_classes=num_classes, name=name, dtype=dtype)
    def update_state(self, y_true, y_pred, sample_weight=None):
        y_true = tf.cast(y_true, tf.int32)
        y_true_squeezed = tf.squeeze(y_true, axis=-1)
        mask = tf.not_equal(y_true_squeezed, -1)
        y_true_masked = tf.boolean_mask(y_true_squeezed, mask)
        y_pred_indices = tf.argmax(y_pred, axis=-1)
        y_pred_masked = tf.boolean_mask(y_pred_indices, mask)
        return super().update_state(y_true_masked, y_pred_masked, sample_weight)

#WSCC Loss, part 1 of the hybrid loss for the model
def weighted_sparse_categorical_crossentropy(weights):
    def loss(y_true, y_pred):
        y_true = tf.cast(y_true, tf.int32)
        y_true = tf.squeeze(y_true, axis=-1)
        valid = tf.cast(tf.not_equal(y_true, -1), tf.float32)
        y_true_safe = tf.where(y_true == -1, 0, y_true)
        pixel_losses = tf.keras.losses.sparse_categorical_crossentropy(y_true_safe, y_pred)
        weight_mask = tf.gather(weights, y_true_safe)
        weight_mask = weight_mask * valid
        return tf.reduce_sum(pixel_losses * weight_mask) / (tf.reduce_sum(weight_mask) + 1e-7)
    return loss

#Dice Loss, part 2 of the hybrid loss for the model
def dice_loss(y_true, y_pred):
    y_true = tf.cast(y_true, tf.int32)
    valid_mask = tf.cast(tf.not_equal(y_true, -1), tf.float32)
    y_true_oh = tf.one_hot(tf.squeeze(y_true, -1), OUTPUT_CHANNELS)
    y_true_oh = tf.cast(y_true_oh, tf.float32)
    y_true_oh = y_true_oh * valid_mask
    y_pred = y_pred * valid_mask
    smooth = 1e-6
    intersection = tf.reduce_sum(y_true_oh * y_pred, axis=(1, 2))
    sum_true = tf.reduce_sum(y_true_oh, axis=(1, 2))
    sum_pred = tf.reduce_sum(y_pred, axis=(1, 2))
    dice = (2. * intersection + smooth) / (sum_true + sum_pred + smooth)
    presence_mask = tf.cast(tf.reduce_sum(y_true_oh, axis=(1, 2)) > 0, tf.float32)
    dice_present = (dice * presence_mask)
    dice_loss_val = 1.0 - (tf.reduce_sum(dice_present, axis=-1) / (tf.reduce_sum(presence_mask, axis=-1) + smooth))
    return tf.reduce_mean(dice_loss_val)

#Combines WSCC Loss and Dice Loss to generate hybrid loss
def hybrid_loss(weights):
    ce_loss_fn = weighted_sparse_categorical_crossentropy(weights)
    def loss(y_true, y_pred):
        return ce_loss_fn(y_true, y_pred) + dice_loss(y_true, y_pred)
    return loss

#Convolutional Block
#Comprised of 2 3x3 convolutions, batch normalization after each convolution. Dropout is only done on the deepest encoder layers
def conv_block(inputs, filters, dropout_rate):
    c = layers.Conv2D(filters, (3, 3), activation='relu', kernel_initializer='he_normal', padding='same')(inputs)
    c = layers.BatchNormalization()(c)
    c = layers.Conv2D(filters, (3, 3), activation='relu', kernel_initializer='he_normal', padding='same')(c)
    c = layers.BatchNormalization()(c)
    if dropout_rate > 0:
        c = layers.SpatialDropout2D(dropout_rate)(c)
    return c

#Upsamling layers used in the decoder section
def upsample_conv(inputs, filters):
    u = layers.UpSampling2D((2, 2), interpolation='bilinear')(inputs)
    u = layers.Conv2D(filters, 3, padding='same', activation='relu')(u)
    return u

#U-Net architecture
#5 Encoder blocks, the first four are followed by 2x2 max pooling for downsampling, the last encoder block acts as a bottleneck
#For each encoder block the number of filters doubled till it gets to filters*16 which is 512 at the bottleneck
#4 Decoder blocks, each one upsamples and then concatenates with the downsampling layer to attempt to recapture any lost features
def unet_model(input_size=(512, 512, 3)):
    inputs = layers.Input(input_size)
    #Encoder/Downsampling
    c1 = conv_block(inputs, NUM_FILTERS, 0)
    p1 = layers.MaxPooling2D((2, 2))(c1)
    c2 = conv_block(p1, NUM_FILTERS * 2, 0)
    p2 = layers.MaxPooling2D((2, 2))(c2)
    c3 = conv_block(p2, NUM_FILTERS * 4, DROPOUT_RATE)
    p3 = layers.MaxPooling2D((2, 2))(c3)
    c4 = conv_block(p3, NUM_FILTERS * 8, DROPOUT_RATE)
    p4 = layers.MaxPooling2D((2, 2))(c4)
    #Bottleneck
    c5 = conv_block(p4, NUM_FILTERS * 16, DROPOUT_RATE)
    #Decoder/Upsampling
    u6 = upsample_conv(c5, NUM_FILTERS * 8)
    u6 = layers.concatenate([u6, c4])
    c6 = conv_block(u6, NUM_FILTERS * 8, 0)
    u7 = upsample_conv(c6, NUM_FILTERS * 4)
    u7 = layers.concatenate([u7, c3])
    c7 = conv_block(u7, NUM_FILTERS * 4, 0)
    u8 = upsample_conv(c7, NUM_FILTERS * 2)
    u8 = layers.concatenate([u8, c2])
    c8 = conv_block(u8, NUM_FILTERS * 2, 0)
    u9 = upsample_conv(c8, NUM_FILTERS)
    u9 = layers.concatenate([u9, c1])
    c9 = conv_block(u9, NUM_FILTERS, 0)
    #Output has 8 channels to label each pixel to 8 classes
    outputs = layers.Conv2D(OUTPUT_CHANNELS, (1, 1), activation='softmax', dtype='float32')(c9)
    return models.Model(inputs=[inputs], outputs=[outputs])

