#Ignore label is added here as well, if during resizing it adds padding hten that pixel is labelled as ignore and is not influenced during training
def load_and_preprocess(img_path, mask_path):
    #Raw image
    img = tf.io.read_file(img_path)
    img = tf.image.decode_jpeg(img, channels=3)
    img = tf.image.resize_with_pad(img, IMG_HEIGHT, IMG_WIDTH)
    #Normalization to 0-1
    img = tf.cast(img, tf.float32) / 255.0
    #Same for mask
    mask = tf.io.read_file(mask_path)
    mask = tf.image.decode_image(mask, channels=3, expand_animations=False)
    mask = rgb_to_class_indices(mask)
    mask = tf.cast(mask, tf.float32) + 1.0
    mask = tf.image.resize_with_pad(mask, IMG_HEIGHT, IMG_WIDTH, method='nearest')
    mask = tf.cast(mask, tf.int32) - 1
    return img, mask
#Data augmentation: randomly scales the image to between 0.75x and 1.25x before resizing to IMG_Height and IMG_width
def random_scale_crop(image, mask):
    scale = tf.random.uniform([], 0.75, 1.25)
    new_h = tf.cast(tf.cast(IMG_HEIGHT, tf.float32) * scale, tf.int32)
    new_w = tf.cast(tf.cast(IMG_WIDTH, tf.float32) * scale, tf.int32)
    image = tf.image.resize(image, [new_h, new_w], method='bilinear')
    mask = tf.image.resize(mask, [new_h, new_w], method='nearest')
    combined = tf.concat([image, tf.cast(mask, tf.float32)], axis=-1)
    combined = tf.image.resize_with_crop_or_pad(combined, IMG_HEIGHT, IMG_WIDTH)
    image = combined[..., :3]
    mask = tf.cast(combined[..., 3:], tf.int32)
    return image, mask
#Additional data augmentation
def augment(image, mask):
    image, mask = random_scale_crop(image, mask)
    #Horizontal Flip (only 50% of images)
    if tf.random.uniform(()) > 0.5:
        image = tf.image.flip_left_right(image)
        mask = tf.image.flip_left_right(mask)
    #Random Birhgtness
    image = tf.image.random_brightness(image, max_delta=0.12)
    #Random conttrast
    image = tf.image.random_contrast(image, lower=0.85, upper=1.15)
    #Random hue
    image = tf.image.random_hue(image, max_delta=0.03)
    #Random saturation
    image = tf.image.random_saturation(image, lower=0.75, upper=1.25)
    #Clipping to ensure pixel values are still valid
    image = tf.clip_by_value(image, 0.0, 1.0)
    return image, mask

