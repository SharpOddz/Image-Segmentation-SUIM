#Converts the raw RGB images into a single channel image with 0-7 indices (one for each class)
def rgb_to_class_indices(mask_rgb):
    mask_binary = tf.cast(mask_rgb > 127, tf.int32)
    r = mask_binary[..., 0]
    g = mask_binary[..., 1]
    b = mask_binary[..., 2]
    class_id = (r * 4) + (g * 2) + b
    return tf.expand_dims(class_id, axis=-1)

