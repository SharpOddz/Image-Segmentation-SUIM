#Calculates foregound IOU, used in the plot title
def calculate_foreground_iou(y_true, y_pred):
    y_true = tf.cast(y_true, tf.int32).numpy().flatten()
    y_pred = y_pred.flatten()
    intersection = np.logical_and(y_true == y_pred, y_true > 0).sum()
    union = np.logical_or(y_true > 0, y_pred > 0).sum()
    return intersection / (union + 1e-6)

